import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { DENOM, SWEEP_THRESHOLDS, THRESHOLD, WEIGHTS, WEIGHT_RATIONALE } from "../src/engine/config";
import { RULES } from "../src/engine/rules";
import { confusionAt, perRuleRecall, sweep } from "../src/engine/metrics";
import { scoreAll } from "../src/engine/score";
import type { Claim, Label } from "../src/engine/types";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "output");

const claims = JSON.parse(readFileSync(join(root, "data", "claims.json"), "utf8")) as Claim[];
const labels = JSON.parse(readFileSync(join(root, "data", "labels.json"), "utf8")) as Label[];
const labelMap = new Map(labels.map((l) => [l.claim_id, l]));

const t0 = performance.now();
const scored = scoreAll(claims);
const elapsedMs = performance.now() - t0;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "scored_output.json"), `${JSON.stringify(scored, null, 2)}\n`);

const chosen = confusionAt(scored, labelMap, THRESHOLD);
const rows = sweep(scored, labelMap, SWEEP_THRESHOLDS);
const ruleRecall = perRuleRecall(scored, labels);

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const meets = chosen.recall >= 0.7 && chosen.fpr <= 0.2;

const report = `# Fraud Detection — Metrics Report

_Generated by \`npm run score\`. Dataset: ${claims.length} claims, ${labels.filter((l) => l.is_fraud).length} planted fraudulent (${pct(labels.filter((l) => l.is_fraud).length / claims.length)})._

## Headline (threshold = ${THRESHOLD})

| Metric | Value | Target | Status |
|---|---|---|---|
| Recall | ${pct(chosen.recall)} | ≥ 70% | ${chosen.recall >= 0.7 ? "PASS" : "FAIL"} |
| False positive rate | ${pct(chosen.fpr)} | ≤ 20% | ${chosen.fpr <= 0.2 ? "PASS" : "FAIL"} |
| Precision | ${pct(chosen.precision)} | — | — |

TP ${chosen.tp} · FP ${chosen.fp} · FN ${chosen.fn} · TN ${chosen.tn}

**${meets ? "Targets met." : "Targets NOT met — retune THRESHOLD / DENOM in src/engine/config.ts."}**

## Threshold sweep

| Threshold | Recall | FPR | Precision | TP | FP | FN |
|---:|---:|---:|---:|---:|---:|---:|
${rows
  .map(
    (r) =>
      `| ${r.threshold}${r.threshold === THRESHOLD ? " ◄ chosen" : ""} | ${pct(r.recall)} | ${pct(r.fpr)} | ${pct(r.precision)} | ${r.tp} | ${r.fp} | ${r.fn} |`,
  )
  .join("\n")}

## Per-rule recall

| Rule | Weight | Caught / Planted | Recall |
|---|---:|---:|---:|
${Object.entries(ruleRecall)
  .map(
    ([rule, { caught, planted }]) =>
      `| ${rule} | ${WEIGHTS[rule as keyof typeof WEIGHTS]} | ${caught} / ${planted} | ${planted ? pct(caught / planted) : "—"} |`,
  )
  .join("\n")}

## Scoring & weight justification

\`risk_score = round(min(rawWeightSum / ${DENOM}, 1) * 100)\`, where \`rawWeightSum\` is the
sum of the severity weights of every triggered rule. A claim is treated as flagged when
\`risk_score >= ${THRESHOLD}\`.

Each weight reflects how strongly a trigger implies *deliberate* fraud (versus a
coincidence or a clerical error), scaled by financial impact:

| Rule | Weight | Why |
|---|---:|---|
${[...RULES].sort((a, b) => b.severity - a.severity)
  .map((r) => `| ${r.name} | ${WEIGHTS[r.name]} | ${WEIGHT_RATIONALE[r.name]} |`)
  .join("\n")}

Low-weight rules are not "unimportant" — they are weak in isolation but push a claim over
the line when several fire together, which is the point of a weighted composite.

\`DENOM = ${DENOM}\` sets the "definitely fraud" ceiling at roughly two of the heaviest rules
firing together. \`THRESHOLD = ${THRESHOLD}\` was picked from the sweep above as the lowest
value that keeps FPR ≤ 20% while maximising recall — insurance economics favour catching
fraud over sparing investigator time.

## Performance

Scored ${claims.length} claims in ${elapsedMs.toFixed(0)} ms (budget: < 30,000 ms).
`;

writeFileSync(join(outDir, "metrics_report.md"), report);

console.log(`Scored ${claims.length} claims in ${elapsedMs.toFixed(0)} ms`);
console.log(`Recall ${pct(chosen.recall)} | FPR ${pct(chosen.fpr)} | Precision ${pct(chosen.precision)}`);
console.log(meets ? "Targets met." : "Targets NOT met.");
console.log("Wrote output/scored_output.json and output/metrics_report.md");
